SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('traveller','admin') NOT NULL DEFAULT 'traveller',
 status ENUM('active','suspended') NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS places (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL, category VARCHAR(60) NOT NULL, region VARCHAR(100) NOT NULL DEFAULT 'Makandura',
 description TEXT NOT NULL, latitude DECIMAL(10,7) NOT NULL, longitude DECIMAL(10,7) NOT NULL,
 route_from_colombo TEXT NOT NULL, conservation_notes TEXT NOT NULL, safety_notes TEXT NOT NULL,
 accessibility TEXT NOT NULL, entry_fee VARCHAR(190) NOT NULL DEFAULT '', opening_hours VARCHAR(190) NOT NULL DEFAULT '',
 contact VARCHAR(190) NOT NULL DEFAULT '', best_time VARCHAR(190) NOT NULL DEFAULT '',
 difficulty VARCHAR(40) NOT NULL DEFAULT 'Easy', visit_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 60,
 status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending', moderation_note TEXT NULL,
 is_demo BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id), INDEX(status,category), INDEX(user_id), INDEX(region)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS place_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, place_id BIGINT UNSIGNED NOT NULL,
 path VARCHAR(500) NOT NULL, caption VARCHAR(190) NOT NULL DEFAULT '',
 FOREIGN KEY(place_id) REFERENCES places(id) ON DELETE CASCADE, INDEX(place_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS services (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, place_id BIGINT UNSIGNED NULL, submitted_by BIGINT UNSIGNED NULL,
 name VARCHAR(160) NOT NULL,
 type ENUM('hospital','police','bus_station','shop','vehicle_rental','tuk_tuk','guide','other') NOT NULL,
 description TEXT NOT NULL, phone VARCHAR(60) NOT NULL DEFAULT '', address VARCHAR(255) NOT NULL DEFAULT '',
 latitude DECIMAL(10,7) NULL, longitude DECIMAL(10,7) NULL, website VARCHAR(500) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(place_id) REFERENCES places(id) ON DELETE CASCADE,
 FOREIGN KEY(submitted_by) REFERENCES users(id) ON DELETE SET NULL, INDEX(type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS saved_places (
 user_id BIGINT UNSIGNED NOT NULL, place_id BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,place_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(place_id) REFERENCES places(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS plans (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL, place_ids JSON NOT NULL,
 start_lat DECIMAL(10,7) NOT NULL, start_lng DECIMAL(10,7) NOT NULL, start_time VARCHAR(5) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS reports (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, place_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NULL,
 reason TEXT NOT NULL, status ENUM('new','resolved','dismissed') NOT NULL DEFAULT 'new',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(place_id) REFERENCES places(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS advertising_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, place_id BIGINT UNSIGNED NULL,
 business_name VARCHAR(160) NOT NULL, contact_name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL, phone VARCHAR(60) NOT NULL, message TEXT NOT NULL,
 status ENUM('new','contacted','closed') NOT NULL DEFAULT 'new',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(place_id) REFERENCES places(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, service_id BIGINT UNSIGNED NULL, service_name VARCHAR(160) NOT NULL DEFAULT '', recorded_by BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(12,2) NOT NULL, reference VARCHAR(190) NOT NULL, paid_on DATE NOT NULL,
 starts_on DATE NOT NULL, ends_on DATE NOT NULL, notes TEXT NOT NULL,
 status ENUM('active','cancelled') NOT NULL DEFAULT 'active', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE SET NULL,
 FOREIGN KEY(recorded_by) REFERENCES users(id), INDEX(service_id,status,starts_on,ends_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS rate_limits (
 bucket VARCHAR(100) PRIMARY KEY, hits INT UNSIGNED NOT NULL DEFAULT 1, resets_at BIGINT UNSIGNED NOT NULL,
 INDEX(resets_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
